import os
import re
from io import BytesIO
from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from fpdf import FPDF
from PIL import Image

LOGO_PATH = os.path.join(os.path.dirname(__file__), "..", "assets", "logo.png")

def sanitize_text(text: str) -> str:
    """Removes unsupported characters and normalizes quotes for clean output generation."""
    text = text.replace("“", '"').replace("”", '"').replace("’", "'").replace("‘", "'")
    text = re.sub(r'[^\x00-\x7F]+', ' ', text)
    return text.strip()

def format_docx(text: str, doc_type: str, terms: str = "") -> BytesIO:
    doc = Document()
    
    # Page setup
    sections = doc.sections
    for section in sections:
        section.top_margin = Inches(1)
        section.bottom_margin = Inches(1)
        section.left_margin = Inches(1)
        section.right_margin = Inches(1)

    # Embed Logo if present
    if os.path.exists(LOGO_PATH):
        p_logo = doc.add_paragraph()
        p_logo.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p_logo.add_run().add_picture(LOGO_PATH, width=Inches(1.8))

    # Document Header Title
    title_p = doc.add_paragraph()
    title_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title_run = title_p.add_run(doc_type.upper())
    title_run.font.name = "Times New Roman"
    title_run.font.size = Pt(18)
    title_run.font.bold = True
    title_run.font.color.rgb = RGBColor(0, 51, 102)

    # Main Body Text
    paragraphs = text.split("\n")
    for para in paragraphs:
        para_clean = para.strip()
        if not para_clean:
            continue
        p = doc.add_paragraph()
        p.paragraph_format.line_spacing = 1.15
        p.paragraph_format.space_after = Pt(6)
        
        # Check for headings
        if para_clean.startswith("**") and para_clean.endswith("**"):
            run = p.add_run(para_clean.replace("**", ""))
            run.font.bold = True
            run.font.name = "Times New Roman"
            run.font.size = Pt(12)
            run.font.color.rgb = RGBColor(0, 51, 102)
        else:
            # Simple bold tag parser
            parts = re.split(r'(\*\*.*?\*\*)', para_clean)
            for part in parts:
                if part.startswith("**") and part.endswith("**"):
                    run = p.add_run(part[2:-2])
                    run.font.bold = True
                else:
                    run = p.add_run(part)
                run.font.name = "Times New Roman"
                run.font.size = Pt(11)

    # Auto-generate dynamic Terms Table if terms exist
    term_list = [t.strip() for t in terms.split(";") if t.strip()]
    if term_list:
        doc.add_paragraph().paragraph_format.space_before = Pt(12)
        table_title = doc.add_paragraph()
        r = table_title.add_run("Key Terms & Conditions Summary")
        r.font.bold = True
        r.font.name = "Times New Roman"
        r.font.size = Pt(12)
        
        table = doc.add_table(rows=1, cols=2)
        table.style = 'Table Grid'
        hdr_cells = table.rows[0].cells
        hdr_cells[0].text = 'Index'
        hdr_cells[1].text = 'Clause / Provision Summary'
        for cell in hdr_cells:
            for p in cell.paragraphs:
                for r in p.runs:
                    r.font.bold = True
                    r.font.name = "Times New Roman"

        for idx, term in enumerate(term_list, 1):
            row_cells = table.add_row().cells
            row_cells[0].text = str(idx)
            row_cells[1].text = term
            for cell in row_cells:
                for p in cell.paragraphs:
                    for r in p.runs:
                        r.font.name = "Times New Roman"

    # Footer
    footer = doc.sections[0].footer
    f_p = footer.paragraphs[0]
    f_p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    f_run = f_p.add_run("Generated by LegalEase AI Platform | Confidential")
    f_run.font.name = "Times New Roman"
    f_run.font.size = Pt(9)
    f_run.font.italic = True

    buffer = BytesIO()
    doc.save(buffer)
    buffer.seek(0)
    return buffer

class PDFGenerator(FPDF):
    def header(self):
        if os.path.exists(LOGO_PATH):
            self.image(LOGO_PATH, x=90, y=8, w=30)
            self.ln(15)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, f"LegalEase AI-Generated Document | Page {self.page_no()}", align="C")

def format_pdf(text: str, doc_type: str) -> BytesIO:
    clean_text = sanitize_text(text)
    pdf = PDFGenerator()
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=15)
    
    # Document Title
    pdf.set_font("Helvetica", "B", 16)
    pdf.set_text_color(0, 51, 102)
    pdf.cell(0, 10, doc_type.upper(), ln=True, align="C")
    pdf.ln(5)

    pdf.set_font("Helvetica", size=10)
    pdf.set_text_color(33, 33, 33)

    paragraphs = clean_text.split("\n")
    for para in paragraphs:
        para_clean = para.strip()
        if not para_clean:
            pdf.ln(3)
            continue
            
        # Format headings
        if para_clean.startswith("**") or para_clean.isupper():
            pdf.ln(2)
            pdf.set_font("Helvetica", "B", 11)
            pdf.set_text_color(0, 51, 102)
            heading_text = para_clean.replace("**", "")
            pdf.multi_cell(0, 6, heading_text)
            pdf.set_font("Helvetica", size=10)
            pdf.set_text_color(33, 33, 33)
        else:
            # Strips residual inline markdown symbols for standard PDF export
            body_text = para_clean.replace("**", "")
            pdf.multi_cell(0, 5, body_text)
            pdf.ln(1)

    buffer = BytesIO()
    pdf_bytes = pdf.output(dest='S')
    buffer.write(pdf_bytes)
    buffer.seek(0)
    return buffer

def format_html_preview(text: str) -> str:
    """Converts output to dark-themed, styled HTML blocks for inline display."""
    formatted_html = text.replace("\n", "<br>")
    formatted_html = re.sub(r'\*\*(.*?)\*\*', r'<strong style="color: #4da6ff;">\1</strong>', formatted_html)
    
    html_wrapper = f"""
    <div style="
        background-color: #1e1e1e;
        color: #d4d4d4;
        font-family: 'Courier New', Courier, monospace;
        padding: 20px;
        border-radius: 8px;
        border: 1px solid #333;
        max-height: 500px;
        overflow-y: auto;
        line-height: 1.6;
        box-shadow: inset 0 0 10px rgba(0,0,0,0.5);
    ">
        {formatted_html}
    </div>
    """
    return html_wrapper